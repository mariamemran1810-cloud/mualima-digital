function showUnit(unit){
  const weeks = unit === "all" ? WEEKS_LIST : WEEKS_LIST.filter(w => w.unit === unit);
  const vis = weeks.map(w => w.week);
  $$("#lessonTabs .tab-btn").forEach(b =>
    b.style.display = vis.includes(+b.dataset.week) ? "" : "none");
  $$("#lessonPanels .tab-panel").forEach(p =>
    p.style.display = vis.includes(+p.dataset.week) ? "" : "none");
  const first = weeks[0];
  if(first){
    $$("#lessonTabs .tab-btn").forEach(b => b.classList.toggle("active", +b.dataset.week === first.week));
    $$("#lessonPanels .tab-panel").forEach(p => p.classList.toggle("active", +p.dataset.week === first.week));
  }
  const total = weeks.reduce((s, w) => s + w.lessons.length, 0);
  $("#lessonCount").textContent =
    `${total} تحضيراً يومياً (${weeks.length} أسبوعاً) — ${unit === "all" ? "جميع الوحدات" : unit}`;
}
$("#unitFilter").addEventListener("click", e => {
  const b = e.target.closest("button");
  if(!b) return;
  $$("#unitFilter button").forEach(x => x.classList.toggle("on", x === b));
  showUnit(b.dataset.unit);
});

